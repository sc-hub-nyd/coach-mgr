import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const root = process.cwd();
const vendorDir = join(root, 'assets/vendor/tabler-icons');
const runtimeJsFiles = (await readdir(root))
    .filter(file => file.endsWith('.js') && file !== 'sw.js')
    .sort();
const sourceFiles = [
    'index.html',
    'CSS/components-system.css',
    'CSS/dashboard.css',
    ...runtimeJsFiles
];

const [tablerCss, ...sources] = await Promise.all([
    readFile(join(vendorDir, 'tabler-icons.css'), 'utf8'),
    ...sourceFiles.map(file => readFile(join(root, file), 'utf8'))
]);

const iconNames = [...new Set(sources.join('\n').match(/\bti-([a-z0-9-]+)\b/g) || [])]
    .map(className => className.slice(3))
    .sort();
const definitions = new Map([...tablerCss.matchAll(/\.ti-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([a-f0-9]+)";\s*\}/g)]
    .map(([, name, codepoint]) => [name, codepoint]));
const missing = iconNames.filter(name => !definitions.has(name));
if (missing.length) throw new Error(`未定義のTablerクラス: ${missing.join(', ')}`);

const unicodeList = iconNames.map(name => `U+${definitions.get(name).toUpperCase()}`);
const subsetCss = `/*\n * CoachMgr runtime Tabler Icons subset. Generated by scripts/build-tabler-subset-v13085.mjs.\n * Source: Tabler Icons 3.46.0 (MIT). Do not edit manually.\n */\n@font-face {\n  font-family: "tabler-icons";\n  font-style: normal;\n  font-weight: 400;\n  src: url("./fonts/tabler-icons-subset.woff2?v=3.46.0-subset.${iconNames.length}") format("woff2");\n}\n\n.ti {\n  font-family: "tabler-icons" !important;\n  speak: none;\n  font-style: normal;\n  font-weight: normal;\n  font-variant: normal;\n  text-transform: none;\n  line-height: 1;\n  -webkit-font-smoothing: antialiased;\n  -moz-osx-font-smoothing: grayscale;\n}\n\n${iconNames.map(name => `.ti-${name}:before {\n  content: "\\${definitions.get(name)}";\n}`).join('\n\n')}\n`;
const manifest = {
    generator: 'scripts/build-tabler-subset-v13085.mjs',
    sourceVersion: 'Tabler Icons 3.46.0',
    sourceFiles,
    iconCount: iconNames.length,
    icons: iconNames,
    unicodeList,
    output: {
        css: 'assets/vendor/tabler-icons/tabler-icons-subset.css',
        font: 'assets/vendor/tabler-icons/fonts/tabler-icons-subset.woff2'
    }
};

await Promise.all([
    writeFile(join(vendorDir, 'tabler-icons-subset.css'), subsetCss),
    writeFile(join(vendorDir, 'subset-unicodes.txt'), `${unicodeList.join(',')}\n`),
    writeFile(join(root, 'reports/tabler-subset-manifest-v13085.json'), `${JSON.stringify(manifest, null, 2)}\n`)
]);
console.log(JSON.stringify({ iconCount: iconNames.length, missing, ...manifest.output }, null, 2));
